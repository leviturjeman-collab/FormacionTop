/**
 * Locale-aware accessor for REAL_AUTOMATIONS. Mirrors the pattern used
 * elsewhere in toolguides.mjs (TOOL_PROFILES_EN, PROFILE_DEFAULT_EN, etc.):
 * a parallel *_EN table, selected by locale, falling back to the Spanish
 * entry if a translation is ever missing for a given index.
 */
export function realAutomationsFor(toolId, locale = 'es') {
  const es = REAL_AUTOMATIONS[toolId]
  if (!es) return undefined
  if (locale !== 'en') return es
  const en = REAL_AUTOMATIONS_EN[toolId]
  if (!en) return es
  return es.map((item, index) => en[index] || item)
}
